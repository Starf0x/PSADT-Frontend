const DICT = { nl: {}, de: {} }
for (const [en, nl, de] of ROWS) { DICT.nl[en] = nl; DICT.de[en] = de }

function initial() {
  try { const s = localStorage.getItem('lang'); if (LANGS.some(([k]) => k === s)) return s } catch { /* storage blocked */ }
  return 'en'
}
let lang = initial()
document.documentElement.lang = lang

export const getLang = () => lang
export function setLang(l) {
  lang = l
  document.documentElement.lang = l
  try { localStorage.setItem('lang', l) } catch { /* storage blocked */ }
}

export function t(s, vars) {
  let r = DICT[lang]?.[s] ?? s
  if (vars) for (const [k, v] of Object.entries(vars)) r = r.replaceAll(`{${k}}`, v)
  return r
}
